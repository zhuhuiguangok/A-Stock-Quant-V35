def to_sw_industry(industry: Optional[str]) -> Optional[str]:
    """把池/持仓的行业名映射为申万一级行业；映射不到返回 None。"""
    if not industry:
        return None
    ind = str(industry).strip()
    if ind in _SW_ALIAS:
        return ind
    for sw, keys in _SW_ALIAS.items():
        for k in keys:
            if k in ind or ind in k:
                return sw
    return None
